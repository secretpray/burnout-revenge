"""Write runtime/kernel/import_stubs.cpp: a logging stub for every kernel/XAM
import the recompiled code references that the runtime doesn't implement yet.

    python3 scripts/gen_import_stubs.py

Import names come from ppc/ppc_recomp_shared.h (XenonRecomp output). An import
counts as implemented if any other runtime source defines it with PPC_FUNC,
GUEST_FUNCTION_HOOK or GUEST_FUNCTION_STUB.
"""
import pathlib
import re
import argparse

ROOT = pathlib.Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--game', choices=['burnout'], default='burnout')
parser.add_argument('--ppc-dir', type=pathlib.Path, default=ROOT / 'ppc')
parser.add_argument('--out', type=pathlib.Path, default=ROOT / 'runtime/kernel/import_stubs.cpp')
args = parser.parse_args()
OUT = args.out.resolve()

imports = sorted(set(re.findall(r'PPC_EXTERN_FUNC\(__imp__(\w+)\)', (args.ppc_dir / 'ppc_recomp_shared.h').read_text())))
implemented = set()
for src in (ROOT / 'runtime').rglob('*.cpp'):
    if src.resolve() == OUT or src.name == 'import_stubs.cpp':
        continue
    if args.game == 'burnout' and (src.parent.name == 'game' or src.name == 'd3d_waits.cpp'):
        continue
    text = src.read_text()
    implemented |= set(re.findall(r'(?:PPC_FUNC|GUEST_FUNCTION_HOOK|GUEST_FUNCTION_STUB)\(\s*__imp__(\w+)', text))

missing = [n for n in imports if n not in implemented]
lines = [
    '// Generated by scripts/gen_import_stubs.py. Do not edit; implement the import',
    '// elsewhere in runtime/ and rerun the script.',
    '// SpeedBreaker runtime. GPL-3.0-or-later (see COPYING).',
    f'// {len(imports)} imports: {len(implemented & set(imports))} implemented, {len(missing)} stubbed.',
    '#include "stdafx.h"',
    '#include "kernel/unimplemented.h"',
    '',
]
lines += [f'PPC_FUNC(__imp__{n}) {{ UnimplementedImport("{n}", ctx, base); }}' for n in missing]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text('\n'.join(lines) + '\n')
print(f'{OUT}: {len(imports)} imports, {len(implemented & set(imports))} implemented, {len(missing)} stubbed')
